#!/usr/bin/env python3
"""Render the field shape of a Kubernetes CRD as Markdown for use as a skill reference.

    scripts/snapshot_crd_shape.py --source "kubevela v1.11.0" [--max-depth 4] [--only spec,status] [--no-header] FILE...

Each FILE is a CRD manifest (YAML, possibly multi-document). For every CRD version marked
`storage: true`, the script walks the OpenAPI v3 schema and prints one line per field with
its type, whether it is required, and the first sentence of its description. Output goes
to stdout so the caller decides the destination file.

The header records the source version so a reader, human or agent, can compare it with the
version reported by `get_platform_info` or `vela version` and know whether the snapshot
matches the cluster in front of them. The header carries no date, so regenerating at the
same tag is byte-identical. Regenerate rather than edit.

Depth is bounded by --max-depth. Where a field has children below that depth, the line
says so explicitly, so a partial shape is never mistaken for a complete one. When none of
the --only fields exist at the top level, as with kinds that declare their fields directly
rather than under spec, every top-level field except apiVersion, kind and metadata is
walked instead and the section says which fields those are.
"""
import argparse
import sys

try:
    import yaml
except ImportError:  # pragma: no cover
    sys.exit("snapshot_crd_shape.py needs PyYAML: pip install pyyaml")

SKIP_TOP = {"apiVersion", "kind", "metadata"}


def first_sentence(text):
    if not text:
        return ""
    text = " ".join(text.split())
    for stop in (". ", ".\n"):
        if stop in text:
            return text.split(stop)[0] + "."
    return text if len(text) < 160 else text[:157] + "..."


def has_children(schema):
    if not isinstance(schema, dict):
        return False
    if schema.get("properties"):
        return True
    for key in ("items", "additionalProperties"):
        sub = schema.get(key)
        if isinstance(sub, dict) and (sub.get("properties") or has_children(sub)):
            return True
    return False


def map_value(schema):
    """Return the value schema of a typed map, or None when the field is not one."""
    extra = schema.get("additionalProperties")
    if isinstance(extra, dict) and not schema.get("properties"):
        return extra
    return None


def type_name(schema):
    typ = schema.get("type") or ("object" if "properties" in schema else "any")
    if typ == "array":
        return "[]" + type_name(schema.get("items") or {})
    value = map_value(schema) if typ == "object" else None
    if value is not None:
        return "map[string]" + type_name(value)
    return typ


def walk(schema, path, depth, max_depth, out, required_here):
    if not isinstance(schema, dict):
        return
    props = schema.get("properties") or {}
    required = set(schema.get("required") or [])
    for name in sorted(props):
        sub = props[name]
        typ = type_name(sub)
        child, seg = sub, ""
        if typ.startswith("[]"):
            child, seg = sub.get("items") or {}, "[]"
        elif typ.startswith("map[string]"):
            child, seg = map_value(sub), "[key]"
        if sub.get("x-kubernetes-preserve-unknown-fields") and typ in ("object", "any"):
            typ = "object (free-form)"
        flag = " required" if name in required else ""
        desc = first_sentence(sub.get("description"))
        full = f"{path}.{name}" if path else name
        suffix = f": {desc}" if desc else ""
        if depth >= max_depth and has_children(child):
            suffix += f" (fields below depth {max_depth} omitted; see `kubectl explain` or the CRD)"
        out.append(f"{'  ' * depth}- `{full}` {typ}{flag}{suffix}")
        if depth < max_depth:
            walk(child, full + seg, depth + 1, max_depth, out, required)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("files", nargs="+")
    ap.add_argument("--source", required=True, help="e.g. 'kubevela v1.11.0'")
    ap.add_argument("--max-depth", type=int, default=4)
    ap.add_argument("--only", default="spec,status", help="comma-separated top-level fields to include")
    ap.add_argument("--no-header", action="store_true", help="omit the generated comment and Source line, for appending to a file that has them")
    args = ap.parse_args()
    only = [s for s in args.only.split(",") if s]

    if not args.no_header:
        print(f"<!-- Generated by scripts/snapshot_crd_shape.py from {args.source}. Regenerate; do not edit. -->")
        print(f"Source: {args.source}")
        print()
    for f in args.files:
        with open(f, encoding="utf-8") as fh:
            for doc in yaml.safe_load_all(fh):
                if not doc or doc.get("kind") != "CustomResourceDefinition":
                    continue
                names = doc["spec"]["names"]
                group = doc["spec"]["group"]
                for ver in doc["spec"].get("versions", []):
                    if not ver.get("storage"):
                        continue
                    schema = (ver.get("schema") or {}).get("openAPIV3Schema") or {}
                    print(f"## {names['kind']} ({group}/{ver['name']}, {doc['spec']['scope'].lower()}-scoped)")
                    print()
                    top = schema.get("properties") or {}
                    fields = [x for x in only if x in top]
                    if not fields:
                        fields = sorted(x for x in top if x not in SKIP_TOP)
                        wanted = ", ".join(f"`{x}`" for x in only)
                        print(f"This kind declares its fields at the top level rather than under {wanted}; "
                              f"the sections below are its top-level fields.")
                        print()
                    for field in fields:
                        out = []
                        walk(top[field], field, 0, args.max_depth, out, set(schema.get("required") or []))
                        print(f"### {field}")
                        print()
                        print("\n".join(out) if out else "- (no schema published; free-form)")
                        print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
